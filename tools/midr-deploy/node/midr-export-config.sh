#!/usr/bin/env bash
# Print the bgpd configuration that advertises MIDR routes to the site
# gateway ("reverse export").  The installer appends it to /etc/midr/bgpd.conf
# when MIDR_ROUTE_EXPORT=yes.
#
#   midr-export-config.sh BGPD_CONF LOCATORS_FILE LOCATOR [ROUTE_TAG]
#
# BGPD_CONF      bgpd configuration holding the site "router bgp ASN" and the
#                iBGP session to the gateway
# LOCATORS_FILE  locator prefixes of all MIDR nodes, one per line
# LOCATOR        this node's transport address
# ROUTE_TAG      tag midrd puts on installed routes (default 199)
#
# MIDR routes are redistributed with no-export, so the gateway uses them
# inside its AS only; this requires the gateway session to be iBGP.  Default
# routes and locator prefixes are never redistributed.
#
# The node also announces its own locator prefix as an ordinary underlay
# route, without no-export.  The gateway passes it to the other sites, where
# it is more specific than the exported site prefix that covers the locator.
# Without it, a remote gateway sends GRE and control traffic for this
# locator back to its own MIDR node, which hands it to the gateway again.
set -euo pipefail

[ "$#" -ge 3 ] && [ "$#" -le 4 ] || {
    echo 'usage: midr-export-config.sh BGPD_CONF LOCATORS_FILE LOCATOR [ROUTE_TAG]' >&2
    exit 2
}
conf=$1
locators=$2
locator=$3
tag=${4:-199}

case "$tag" in
    ''|*[!0-9]*|0) echo "route tag must be a positive integer: $tag" >&2; exit 2 ;;
esac
asn=$(awk '$1 == "router" && $2 == "bgp" && $3 ~ /^[0-9]+$/ && NF == 3 { print $3; exit }' "$conf")
[ -n "$asn" ] || { echo "no default-VRF \"router bgp ASN\" in $conf" >&2; exit 1; }
awk -v asn="$asn" '$1 == "neighbor" && $3 == "remote-as" && ($4 == asn || $4 == "internal") { found = 1 }
    END { exit !found }' "$conf" || {
    echo "route export needs an iBGP gateway session (neighbor remote-as $asn) in $conf" >&2
    exit 1
}
[ -r "$locators" ] || { echo "locator file is not readable: $locators" >&2; exit 1; }
own=$(python3 -c '
import ipaddress, sys
address = ipaddress.ip_address(sys.argv[1])
for line in open(sys.argv[2], encoding="utf-8"):
    text = line.split("#", 1)[0].strip()
    if text and address in ipaddress.ip_network(text):
        print(ipaddress.ip_network(text))
        break
' "$locator" "$locators")
[ -n "$own" ] || { echo "locator $locator is not covered by $locators" >&2; exit 1; }
case "$own" in
    *:*) own_family=ipv6 ;;
    *) own_family=ipv4 ;;
esac

echo '! MIDR route export, generated by midr-export-config.sh'
echo 'ip prefix-list MIDR-EXPORT-DENY4 seq 5 permit 0.0.0.0/0'
echo 'ipv6 prefix-list MIDR-EXPORT-DENY6 seq 5 permit ::/0'
seq4=10
seq6=10
while IFS= read -r line; do
    prefix=${line%%#*}
    prefix=${prefix//[[:space:]]/}
    [ -n "$prefix" ] || continue
    case "$prefix" in
        *:*) echo "ipv6 prefix-list MIDR-EXPORT-DENY6 seq $seq6 permit $prefix le 128"
             seq6=$((seq6 + 5)) ;;
        *)   echo "ip prefix-list MIDR-EXPORT-DENY4 seq $seq4 permit $prefix le 32"
             seq4=$((seq4 + 5)) ;;
    esac
done <"$locators"
cat <<EOF
route-map MIDR-EXPORT deny 10
 match ip address prefix-list MIDR-EXPORT-DENY4
exit
route-map MIDR-EXPORT deny 20
 match ipv6 address prefix-list MIDR-EXPORT-DENY6
exit
route-map MIDR-EXPORT permit 30
 match tag $tag
 set community no-export additive
exit
router bgp $asn
 address-family $own_family unicast
  network $own
 exit-address-family
 address-family ipv4 unicast
  redistribute midr route-map MIDR-EXPORT
 exit-address-family
 address-family ipv6 unicast
  redistribute midr route-map MIDR-EXPORT
 exit-address-family
exit
EOF
