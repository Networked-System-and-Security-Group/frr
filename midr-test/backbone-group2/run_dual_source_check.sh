#!/usr/bin/env bash
# =============================================================================
# 轮 4 档 2 判据：第二组对接的双源一致性 + 上报线健康度
#
# 跑法：bash run_dual_source_check.sh   （台子须已冷启动并收敛，PM 热身完成）
# 前提：15 节点骨干台子（midr-backbone），合栈二进制已部署。
#
# 判据来源：轮4/轮4开工plan.md 档 2 + 轮4/plan-resync议题.md §9。
# 与 backbone-discovery 的分工：那份验发现链行为，本份只验"我方与第二组之间
# 这条数据通道"对不对。
# =============================================================================

PASS=0; FAIL=0; NOSAM=0
pass() { echo "  ✓ $1"; PASS=$((PASS+1)); }
fail() { echo "  ✗ $1"; FAIL=$((FAIL+1)); }
nosam() { echo "  ⚠ 没造出场景：$1"; NOSAM=$((NOSAM+1)); }

C=clab-midr-backbone
v() { docker exec $1 vtysh -c "$2" 2>/dev/null; }
g2() { v $1 "show midr group2"; }
# 取 show midr group2 里某个数字字段
g2num() { g2 $1 | grep -oP "$2\K[0-9]+" | head -1; }

MEMBERS="$C-m1a $C-m1b $C-r1 $C-r2 $C-z1 $C-z2 $C-m2a"
BOOTSTRAPS="$C-b1 $C-b2 $C-b3 $C-b4 $C-b5"

echo "=============================================================="
echo " 轮 4 档 2 判据 —— 第二组接口双源一致性"
echo "=============================================================="

# ---------------------------------------------------------------------------
# 判据 G1：回调注册（件③ 的地基；没注册则下面所有下行判据无意义）
# ---------------------------------------------------------------------------
echo
echo "[判据 G1] remote-view 回调已注册"
BAD=""
for c in $MEMBERS; do
    g2 $c | grep -q "回调注册        : 已注册" || BAD="$BAD ${c##*-}"
done
[ -z "$BAD" ] && pass "判据G1：7 个成员节点回调全部注册" \
              || fail "判据G1：未注册 →$BAD"

# ---------------------------------------------------------------------------
# 判据 G2：双源逐字段一致（B-4 拍板的核心判据）
#
# ⚠⚠ 【件②（轮 4）起本判据失去对象，已降为 nosam —— 别把它当通过】
#   它读的是 midr_nds_remote_compare() 维护的"双源不一致"计数器，而那个函数比的是
#   「第二组回调值 vs 节点表现值」。件② 删掉自有 NLRI 收包线之后，**节点表里的值就是
#   回调自己写进去的**，比较变成自己跟自己比，计数器恒为 0。
#
#   恒 0 → 判据恒"通过"，但那是**假 PASS**：它不再证明任何东西，却长得跟健康一模一样
#   （比假 NOSAMPLE 更危险——NOSAMPLE 至少会提示"没造出场景"）。所以这里主动降档。
#
#   ⚠ 计数器与 compare 函数本身**保留不删**（plan 条 27）：万一将来要 checkout 件②
#   之前的提交复跑双源对照，那套东西还得在。
#   触发恢复：真正出现第二个独立数据源时（例如 gossip C 计划落地）。
# ---------------------------------------------------------------------------
echo
echo "[判据 G2] 双源逐字段一致（件② 后已无第二个源）"
TOTAL=0; BAD=""
for c in $MEMBERS; do
    N=$(g2num $c "双源不一致      : ")
    N=${N:-0}; TOTAL=$((TOTAL+N))
    [ "$N" -gt 0 ] && BAD="$BAD ${c##*-}=$N"
done
if [ "$TOTAL" -gt 0 ]; then
    # 恒 0 是预期；真冒出非 0 反而是新信息（说明还有别的东西在写节点表）
    fail "判据G2：共 $TOTAL 处不一致 →$BAD —— 件② 后本该恒 0，非 0 说明节点表还有第二个写入方，查 'MIDR 双源对照'"
else
    nosam "判据G2：件② 删掉旧 NLRI 源后已无第二个源可对照（计数器恒 0，不算通过）"
fi

# ---------------------------------------------------------------------------
# 判据 G3：上行 node 上报成功且无欠账
#   pending=1 表示上报被第二组拒了还没补上；稳态下必须为 0。
# ---------------------------------------------------------------------------
echo
echo "[判据 G3] node 上报：已报且无 pending 欠账"
BAD=""
for c in $MEMBERS; do
    LINE=$(g2 $c | grep "node            :")
    echo "$LINE" | grep -q "reported=1" || BAD="$BAD ${c##*-}(未报)"
    echo "$LINE" | grep -q "pending=0"  || BAD="$BAD ${c##*-}(有欠账)"
done
[ -z "$BAD" ] && pass "判据G3：7 个成员 node 均已上报、零 pending" \
              || fail "判据G3：$BAD"

# ---------------------------------------------------------------------------
# 判据 G4：引导节点专职化 —— 不上报自己
#   引导只转发不自产（facts.c 的 is_bootstrap 守卫）。
# ---------------------------------------------------------------------------
echo
echo "[判据 G4] 引导节点不上报自身 node"
BAD=""
for c in $BOOTSTRAPS; do
    g2 $c | grep "node            :" | grep -q "reported=0" || BAD="$BAD ${c##*-}"
done
[ -z "$BAD" ] && pass "判据G4：5 台引导均未上报自身（专职化守卫生效）" \
              || fail "判据G4：以下引导上报了自己 →$BAD"

# ---------------------------------------------------------------------------
# 判据 G5：link 上报到达第二组 LSDB，且本机"报出去还活着"的条数与之对得上
#
# ⚠ 比的是 reported 数，不是条目总数（2026-08-23 件④ 改）：撤销后事实表**保留
# 条目当墓碑**、只把 reported 翻假（轮 3 定的口径，见 midr-group2-snapshot-
# provider.md），所以总数 ≥ reported。件② 时两者恰好相等（没有边被撤过），件④
# 掉沿清账后拆边更快、墓碑常态存在，拿总数比就会误报"不一致"。
# ---------------------------------------------------------------------------
echo
echo "[判据 G5] link 上报：事实表 reported 数 == 第二组 owned 条数"
BAD=""
for c in $C-r1 $C-m1a $C-m1b; do
    FACT=$(g2 $c | grep -oP "link            : 条目 [0-9]+（reported \K[0-9]+")
    TOMB=$(g2 $c | grep -oP "link            : 条目 \K[0-9]+")
    OWNED=$(v $c "show midr owned" | grep -oP "^\s+links:\s+\K[0-9]+")
    SUPP=$(v $c "show midr owned" | grep -oP "suppressed links:\s+\K[0-9]+")
    SUPP=${SUPP:-0}
    [ "${FACT:-x}" = "${OWNED:-y}" ] || \
        BAD="$BAD ${c##*-}(reported$FACT/owned$OWNED,条目$TOMB,抑制$SUPP)"
done
[ -z "$BAD" ] && pass "判据G5：3 个受检节点两侧条数一致（reported vs owned）" \
              || fail "判据G5：$BAD"

# ---------------------------------------------------------------------------
# 判据 G6：建边占位首报（A-2）—— 会话建立即有 link，不等 PM 60s 热身
#   正样本形态 = 第二组视图里出现 rtt-us 100000 / loss-ppm 100000 且 version 1。
#   ⚠ 稳态下占位值会被 PM 真值覆盖，所以本判据只在"存在尚未探通的边"时有样本。
# ---------------------------------------------------------------------------
echo
echo "[判据 G6] 建边占位首报（rtt 100ms / loss 10% 的占位指标）"
PLACE=$(for c in $MEMBERS; do
            v $c "show midr topology links" | grep -c "rtt-us 100000 loss-ppm 100000"
        done | awk '{s+=$1} END {print s+0}')
COVERED=$(for c in $MEMBERS; do
            v $c "show midr topology links" | grep -c "loss-ppm 0 "
          done | awk '{s+=$1} END {print s+0}')
if [ "$PLACE" -gt 0 ]; then
    pass "判据G6：占位指标在第二组视图中可见（$PLACE 条尚未被真值覆盖）"
elif [ "$COVERED" -gt 0 ]; then
    nosam "全部边的占位值都已被 PM 真值覆盖（$COVERED 条真值边）——占位机制无法反证，需在会话刚建立的窗口内采样"
else
    fail "判据G6：既无占位值也无真值，link 上报可能整体没通"
fi

# ---------------------------------------------------------------------------
# 判据 G7：撤销后短窗内又被通告（虚报探针）——只观察不判失败
#   机制见问题清单 #16：BGP 撤销不带序号，旧副本经备份路径复活。
#   稳态下应为 0；退网实验后可能非 0，属已知现象，故不计失败。
# ---------------------------------------------------------------------------
echo
echo "[判据 G7] 虚报探针（观察项，不判失败）"
SUS=0
for c in $MEMBERS; do
    N=$(g2num $c "疑似虚报撤销    : "); SUS=$((SUS+${N:-0}))
done
echo "      疑似虚报累计 $SUS 次（稳态期望 0；退网实验后非 0 属已知现象，见问题清单 #16）"

# ---------------------------------------------------------------------------
# 判据 G8：无配置群号的节点，其"群号 0 窗口"不影响 join
#   B-8 守卫按运行值群号非 0 才上报，无配置节点入网前恒为 0、上报全被挡；
#   而 join 链走引导名单 + 5859 控制通道、不依赖第二组泛洪，故应照常完成
#   （轮4开工plan 档 2 末句 + 答 63）。
#   两半合起来才成立：① 窗口确实存在过（有抑制日志）；② join 仍然成功。
#   ⚠ ① 是 debug 档日志，未开 debug 时取不到样本，此时只报 ② 并计 NOSAMPLE。
# ---------------------------------------------------------------------------
echo
echo "[判据 G8] 无配置节点的群号 0 窗口不影响 join"
JOINED=0
for c in $C-z1 $C-z2; do
    GID=$(v $c "show midr self" | awk -F: '/^Group-ID/{gsub(/ /,"",$2);print $2}')
    v $c "show midr self" >/dev/null 2>&1 || continue
    [ "${GID:-0}" != "0" ] && JOINED=$((JOINED+1))
done
SUPPRESS=$(for c in $C-z1 $C-z2; do
               docker exec $c grep -c "尚未入群（群号 0），node 上报抑制" \
                   /etc/frr/logs/frr.log 2>/dev/null || echo 0
           done | awk '{s+=$1} END {print s+0}')
if [ "$JOINED" -eq 2 ] && [ "$SUPPRESS" -gt 0 ]; then
    pass "判据G8：z1/z2 均已入群，且窗口期上报确被守卫抑制（$SUPPRESS 次）"
elif [ "$JOINED" -eq 2 ]; then
    nosam "z1/z2 均已入群，但抑制日志取不到（debug 未开），窗口存在性无法反证"
else
    fail "判据G8：z1/z2 只有 $JOINED 台入群（群号仍为 0）"
fi

echo
echo "=============================================================="
echo " 结果：通过 $PASS，失败 $FAIL，没造出场景 $NOSAM"
echo "=============================================================="
[ "$FAIL" -eq 0 ]
